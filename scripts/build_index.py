#!/usr/bin/env python3
"""Generate INDEX.md and index.json (catalog of every tool folder) and flag .json files that aren't strict JSON.

Usage: python3 scripts/build_index.py [--check]
  --check  exit non-zero if INDEX.md/index.json are stale .
"""
import json, sys, urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"assets", "scripts", ".github", ".git"}
PROMPT_EXT = {".txt", ".md", ".yaml", ".yml", ".json"}

def link(p: Path) -> str:
    return urllib.parse.quote(p.relative_to(ROOT).as_posix())

def build():
    tools, errors, bad = [], [], set()
    for d in sorted((x for x in ROOT.iterdir() if x.is_dir() and x.name not in SKIP and not x.name.startswith(".")),
                    key=lambda x: x.name.lower()):
        files = []
        for f in sorted(d.rglob("*")):
            if f.is_file() and f.suffix.lower() in PROMPT_EXT:
                if f.suffix.lower() == ".json":
                    try: json.loads(f.read_text(encoding="utf-8"))
                    except Exception as e: errors.append(f"{f.relative_to(ROOT)}: {e}"); bad.add(f)
                files.append({"path": f.relative_to(ROOT).as_posix(), "bytes": f.stat().st_size,
                              "type": ("tools-invalid-json" if f in bad else "tools") if f.suffix.lower() == ".json" else "prompt"})
        tools.append({"name": d.name, "files": files})
    lines = ["# Index", "", "_Auto-generated by `scripts/build_index.py` — do not edit by hand._", "",
             f"**{len(tools)} tools/vendors, {sum(len(t['files']) for t in tools)} files.**", "",
             "| Tool | Files |", "|---|---|"]
    for t in tools:
        cells = "<br>".join(f"[{Path(f['path']).relative_to(t['name']).as_posix()}]({urllib.parse.quote(f['path'])}) ({f['bytes']/1024:.1f} KB){' ⚠️ not strict JSON' if f['type']=='tools-invalid-json' else ''}"
                            for f in t["files"])
        lines.append(f"| **{t['name']}** | {cells} |")
    return "\n".join(lines) + "\n", json.dumps(tools, indent=2) + "\n", errors

def main():
    md, js, errors = build()
    for e in errors: print("warning: not strict JSON:", e, file=sys.stderr)
    if "--check" in sys.argv:
        stale = (ROOT/"INDEX.md").read_text() != md or (ROOT/"index.json").read_text() != js
        if stale: print("INDEX.md/index.json are stale; run scripts/build_index.py", file=sys.stderr)
        sys.exit(1 if stale else 0)
    (ROOT/"INDEX.md").write_text(md); (ROOT/"index.json").write_text(js)
    print(f"Wrote INDEX.md and index.json ({len(js.splitlines())} lines)")

if __name__ == "__main__":
    main()
